import torch
import math
from instrument_detection.models.model import build_model
from instrument_detection.config import N_HARMONICS, N_BINS, CQT_HOP, SAMPLE_RATE, FRAME_SIZE_MS

OUTPUT_HEADER_FILE = "../c/include/model_params.h"

def get_layer_params_and_print(module_name, module, c_in, h_in, w_in):
    """
    Analyzes a Conv layer, prints the dimensions of the layer, and returns its C-struct definition and output shape.
    Extracts the Conv layer parameters for both the 1D and 2D Conv cases.
    Returns None if the module is not a Conv layer.
    """
    if not isinstance(module, (torch.nn.Conv2d, torch.nn.Conv1d)):
        return None, (c_in, h_in, w_in)

    k_out = module.out_channels

    if isinstance(module, torch.nn.Conv2d):
        kernel = module.kernel_size if isinstance(module.kernel_size, tuple) else (module.kernel_size, module.kernel_size)
        stride = module.stride if isinstance(module.stride, tuple) else (module.stride, module.stride)
        padding = module.padding if isinstance(module.padding, tuple) else (module.padding, module.padding)
    else:
        kernel = (1, module.kernel_size[0])
        stride = (1, module.stride[0])
        padding = (0, module.padding[0])

    # General formula is: (dim + 2 * pad_dim - kernel_dim) // stride_dim + 1 (Check lab book)
    out_h = (h_in + 2 * padding[0] - kernel[0]) // stride[0] + 1
    out_w = (w_in + 2 * padding[1] - kernel[1]) // stride[1] + 1

    c_struct = f"""
                // Layer: {module_name}
                {{
                    .n_in=1, .c_in={c_in}, .h_in={h_in}, .w_in={w_in},
                    .k_out={k_out}, .kernel_h={kernel[0]}, .kernel_w={kernel[1]},
                    .pad_h={padding[0]}, .pad_w={padding[1]}, .stride_h={stride[0]}, .stride_w={stride[1]},
                    .n_out=1, .c_out={k_out}, .h_out={out_h}, .w_out={out_w}
                }}"""
    print(f"  - Processed layer '{module_name}': Input=({c_in},{h_in},{w_in}), Output=({k_out},{out_h},{out_w})")

    return c_struct, (k_out, out_h, out_w)


def main():
    cqt_time_step_s = CQT_HOP / SAMPLE_RATE
    frame_duration_s = FRAME_SIZE_MS / 1000.0
    TIME_STEPS = int(math.ceil(frame_duration_s / cqt_time_step_s))

    model = build_model()
    model.eval()

    c_header_content = f"""//
// THIS FILE IS AUTO-GENERATED BY export_model_architecture.py. DO NOT EDIT.
//

#ifndef MODEL_PARAMS_H
#define MODEL_PARAMS_H

#include "cpu_layers.h"

"""

    backbone_layers = []
    current_dims = (N_HARMONICS, TIME_STEPS, N_BINS)
    for name, module in model.backbone.named_modules():
        if isinstance(module, (torch.nn.Conv2d)):
            c_struct, new_dims = get_layer_params_and_print(f"backbone.{name}", module, *current_dims)
            if c_struct:
                backbone_layers.append(c_struct)
                current_dims = new_dims

    backbone_output_dims = current_dims

    c_header_content += f"#define NUM_BACKBONE_LAYERS {len(backbone_layers)}\n"
    c_header_content += f"static const LayerParams backbone_architecture[NUM_BACKBONE_LAYERS] = {{{','.join(backbone_layers)}}};\n\n"

    head_names = ['piano', 'strings', 'woodwinds', 'brass']
    for head in head_names:
        print(f"\n--- Processing {head.capitalize()} Head ---")
        head_layers = []
        current_dims = backbone_output_dims

        aggregator_component = getattr(model, f"{head}_aggregator")
        classifier_component = getattr(model, f"{head}_classifier")

        for name, module in aggregator_component.named_modules():
            if isinstance(module, (torch.nn.Conv2d, torch.nn.Conv1d)):
                c_struct, new_dims = get_layer_params_and_print(f"{head}_aggregator.{name}", module, *current_dims)
                if c_struct:
                    head_layers.append(c_struct)
                    current_dims = new_dims

        current_dims = (current_dims[0], current_dims[1], 1)
        print(f"Applying Squeeze: New Shape for Classifier Input=({current_dims[0]},{current_dims[1]},{current_dims[2]})")
        c_struct, new_dims = get_layer_params_and_print(f"{head}_classifier", classifier_component, *current_dims)

        if c_struct:
            head_layers.append(c_struct)

        c_header_content += f"#define NUM_{head.upper()}_HEAD_LAYERS {len(head_layers)}\n"
        c_header_content += f"static const LayerParams {head}_head_architecture[NUM_{head.upper()}_HEAD_LAYERS] = {{{','.join(head_layers)}}};\n\n"

    c_header_content += "#endif //MODEL_PARAMS_H\n"

    with open(OUTPUT_HEADER_FILE, "w") as f:
        f.write(c_header_content)

    print(f"\n--- SUCCESS: C header file written to '{OUTPUT_HEADER_FILE}' ---")


if __name__ == '__main__':
    main()